const { test } = require('node:test');
const assert = require('node:assert/strict');
const images = require('../services/images');

test('generated bytes upload to public Storage, failures and missing keys safely fall back', async t => {
  const originalFetch = global.fetch;
  const keys = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY', 'IMAGE_API_KEY', 'IMAGE_API_BASE', 'SUPABASE_COVERS_BUCKET'];
  const previous = Object.fromEntries(keys.map(key => [key, process.env[key]]));
  t.after(() => { global.fetch = originalFetch; for (const key of keys) previous[key] === undefined ? delete process.env[key] : process.env[key] = previous[key]; });
  process.env.SUPABASE_URL = 'https://mock-project.supabase.co';
  process.env.SUPABASE_SERVICE_ROLE_KEY = 'mock-service-key';
  process.env.IMAGE_API_KEY = 'mock-image-key';
  process.env.IMAGE_API_BASE = 'https://quanzil.com/v1';
  process.env.SUPABASE_COVERS_BUCKET = 'shiguang-covers';
  const png = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10, 0, 1]);
  let exists = false;
  let failUpload = false;
  let privateBucket = false;
  let generated = { b64_json: png.toString('base64') };
  let uploads = 0;
  let creates = 0;
  let calls = 0;
  global.fetch = async (url, options = {}) => {
    calls++;
    const parsed = new URL(url);
    if (parsed.hostname === 'quanzil.com') {
      if (parsed.pathname === '/cover.png') return new Response(png);
      return Response.json({ data: [generated] });
    }
    assert.equal(parsed.hostname, 'mock-project.supabase.co');
    const headers = new Headers(options.headers);
    assert.equal(headers.get('authorization'), 'Bearer mock-service-key');
    if (parsed.pathname === '/storage/v1/bucket/shiguang-covers') {
      return exists ? Response.json({ id: 'shiguang-covers', public: !privateBucket }) : Response.json({ message: 'Bucket not found', statusCode: '404' }, { status: 404 });
    }
    if (parsed.pathname === '/storage/v1/bucket') {
      assert.equal(JSON.parse(options.body).public, true);
      exists = true; creates++;
      return Response.json({ name: 'shiguang-covers' });
    }
    assert.match(parsed.pathname, /^\/storage\/v1\/object\/shiguang-covers\/poems\/[a-f0-9-]+\.png$/);
    assert.equal(headers.get('content-type'), 'image/png');
    uploads++;
    return failUpload ? Response.json({ message: 'upload failed' }, { status: 500 }) : Response.json({ Key: parsed.pathname });
  };
  const cover = await images.generateCover('一首诗');
  assert.match(cover, /^https:\/\/mock-project\.supabase\.co\/storage\/v1\/object\/public\/shiguang-covers\/poems\/[a-f0-9-]+\.png$/);
  assert.equal(creates, 1);
  assert.equal(uploads, 1);
  generated = { url: 'https://quanzil.com/cover.png' };
  assert.match(await images.generateCover('URL图片'), /storage\/v1\/object\/public/);
  assert.equal(uploads, 2);
  failUpload = true;
  assert.equal(await images.generateCover('上传失败'), images.DEFAULT_COVER);
  failUpload = false;
  privateBucket = true;
  assert.equal(await images.generateCover('私有桶'), images.DEFAULT_COVER);
  privateBucket = false;
  generated = { b64_json: Buffer.from('<script>bad</script>').toString('base64') };
  const beforeInvalid = uploads;
  assert.equal(await images.generateCover('非法图片'), images.DEFAULT_COVER);
  assert.equal(uploads, beforeInvalid);
  process.env.SUPABASE_SERVICE_ROLE_KEY = '';
  const beforeMissing = calls;
  assert.equal(await images.generateCover('无存储key'), images.DEFAULT_COVER);
  assert.equal(calls, beforeMissing);
  process.env.SUPABASE_SERVICE_ROLE_KEY = 'mock-service-key';
  process.env.IMAGE_API_KEY = '';
  assert.equal(await images.generateCover('无生图key'), images.DEFAULT_COVER);
  assert.equal(calls, beforeMissing);
});
