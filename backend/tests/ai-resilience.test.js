const { test } = require('node:test');
const assert = require('node:assert/strict');
process.env.SUPABASE_URL = '';
process.env.SUPABASE_SERVICE_ROLE_KEY = '';
const db = require('../services/database');
const ai = require('../services/ai');
const security = require('../services/contentSecurity');
const service = require('../services/companionAI');

test('empty materials and summary failures remain usable; poem errors provide safe guidance', async t => {
  const originals = [];
  const replace = (object, key, value) => { originals.push([object, key, object[key]]); object[key] = value; };
  t.after(() => { for (const [object, key, value] of originals.reverse()) object[key] = value; security.resetChecker(); });
  const volunteer = { id: 'v', role: 'volunteer', status: 'active', openid: 'o' };
  const student = { id: 's', name: '张小明' };
  let logs = [];
  let summaryCalls = 0;
  let generateCalls = 0;
  let writes = 0;
  let rejectOutput = false;
  let failGeneration = false;
  replace(db, 'listRecords', async () => [{ commentOverall: '   ' }]);
  replace(db, 'listCompanionLogs', async () => logs);
  replace(db, 'listAiSuggestions', async () => []);
  replace(db, 'createAiSuggestion', async value => { writes++; return value; });
  replace(db, 'createGrowthPoem', async () => { throw new Error('Fallback must not persist'); });
  replace(ai, 'summarizeRecords', async () => { summaryCalls++; throw Object.assign(new Error('摘要结构无效'), { status: 502 }); });
  replace(ai, 'generateSuggest', async context => {
    generateCalls++;
    if (failGeneration) throw Object.assign(new Error('生成结构无效'), { status: 502 });
    assert.ok(context.recentLogs.length > 0);
    assert.ok(context.recentLogs.every(value => value.length <= 200));
    assert.equal(JSON.stringify(context.recentLogs).includes('张小明'), false);
    return { status: '倾听孩子', openers: ['想聊聊吗', '我在这里'], activities: ['散步', '折纸', '画画'], cautions: ['尊重意愿', '不强迫'], disclaimer: ai.DISCLAIMER };
  });
  replace(ai, 'generatePoem', async () => { throw Object.assign(new Error('成长诗结构无效'), { status: 502 }); });
  security.setChecker(async ({ content }) => ({ allowed: !(rejectOutput && content.includes('倾听孩子')) }));
  const empty = await service.generateSuggest(student, volunteer);
  assert.match(empty.status, /当前缺少成长记录，建议先补充陪伴记录/);
  assert.equal(empty.disclaimer, ai.DISCLAIMER);
  assert.equal(summaryCalls, 0);
  assert.equal(generateCalls, 0);
  assert.equal(writes, 0);
  await assert.rejects(service.generatePoem(student, volunteer, '本期'), error => error.status === 422 && /请先添加陪伴记录/.test(error.message));
  logs = [{ type: '探访', content: '张小明分享了作品' }];
  const continued = await service.generateSuggest(student, volunteer);
  assert.equal(continued.status, '倾听孩子');
  assert.equal(summaryCalls, 1);
  assert.equal(writes, 1);
  logs = [{ type: '探访', content: '记'.repeat(1501) + '不想活' }];
  rejectOutput = true;
  const crisis = await service.generateSuggest(student, volunteer);
  assert.ok(crisis.status.includes(ai.CRISIS_GUIDANCE));
  assert.ok(crisis.cautions.includes(ai.CRISIS_GUIDANCE));
  assert.equal(writes, 1);
  failGeneration = true;
  const failedBoth = await service.generateSuggest(student, volunteer);
  assert.ok(failedBoth.status.includes(ai.CRISIS_GUIDANCE));
  assert.equal(writes, 1);
  const poemFallback = await service.generatePoem(student, volunteer, '本期');
  assert.equal(poemFallback.title, '静待成长');
  // Check actual HTTP semantics without invoking a real provider or storage.
  replace(db, 'findSession', async () => ({ token: '1'.repeat(64), volunteerId: 'v', expiresAt: '2099-01-01' }));
  replace(db, 'findVolunteerById', async () => volunteer);
  replace(db, 'hasRelation', async () => true);
  replace(db, 'findStudent', async () => student);
  const { createApp } = require('../server');
  const server = createApp().listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const call = async kind => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/app/ai/${kind}`, { method: 'POST', headers: { Authorization: `Bearer ${'1'.repeat(64)}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ studentId: 's', period: '本期' }) });
    return { status: response.status, body: await response.json() };
  };
  logs = [];
  assert.equal((await call('suggest')).status, 200);
  const noPoem = await call('poem');
  assert.equal(noPoem.status, 422);
  assert.match(noPoem.body.message, /请先添加陪伴记录/);
  logs = [{ type: '探访', content: '分享作品' }];
  assert.equal((await call('poem')).status, 200);
});
