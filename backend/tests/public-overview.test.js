const { test } = require('node:test');
const assert = require('node:assert/strict');
process.env.SUPABASE_URL = '';
process.env.SUPABASE_SERVICE_ROLE_KEY = '';
const db = require('../services/database');
const { createApp } = require('../server');
test('public scope-only statistics never disclose score or grade changes', async t => {
  const originals = { listStudents: db.listStudents, listRecords: db.listRecords };
  let score = 20;
  db.listStudents = async () => Array.from({ length: 10 }, (_, i) => ({ id: String(i), name: '秘密姓名', school: '秘密学校' }));
  db.listRecords = async () => Array.from({ length: 10 }, (_, i) => ({ id: String(i), studentId: String(i), psychology: score, aesthetic: score, finance: score, behavior: score }));
  const server = createApp().listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { Object.assign(db, originals); await new Promise(resolve => server.close(resolve)); });
  const get = async () => (await (await fetch(`http://127.0.0.1:${server.address().port}/api/app/public/overview`)).json()).data;
  const before = await get();
  assert.deepEqual(before, { studentCount: 10, schoolCount: 1, recordCount: 10 });
  score = 90;
  assert.deepEqual(await get(), before);
});
