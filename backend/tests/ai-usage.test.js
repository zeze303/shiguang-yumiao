const { test } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const usage = require('../services/aiUsage');
test('account reservation, concurrency, budget and idempotency block duplicate cost', async t => {
  const old = Object.fromEntries(['AI_MAX_CONCURRENCY', 'AI_ACCOUNT_DAILY_LIMIT', 'AI_GLOBAL_DAILY_UNITS'].map(k => [k, process.env[k]]));
  t.after(() => { for (const [k, v] of Object.entries(old)) v === undefined ? delete process.env[k] : process.env[k] = v; });
  process.env.AI_MAX_CONCURRENCY = '1';
  process.env.AI_ACCOUNT_DAILY_LIMIT = '1';
  process.env.AI_GLOBAL_DAILY_UNITS = '100000';
  const account = crypto.randomUUID(), key = crypto.randomUUID();
  let release;
  const held = new Promise(resolve => { release = resolve; });
  let calls = 0;
  const task = async () => { calls++; await held; return { result: 'ok' }; };
  const first = usage.run(account, key, { kind: 'suggest' }, task);
  const duplicate = usage.run(account, key, { kind: 'suggest' }, task);
  await new Promise(resolve => setTimeout(resolve, 50));
  await assert.rejects(usage.run('other-' + account, crypto.randomUUID(), {}, task), e => e.status === 429);
  await assert.rejects(usage.run(account, key, { kind: 'poem' }, task), e => e.status === 409);
  release();
  assert.deepEqual(await first, await duplicate);
  assert.equal(calls, 1);
  assert.deepEqual(await usage.run(account, key, { kind: 'suggest' }, task), { result: 'ok' });
  assert.equal(calls, 1);
  await assert.rejects(usage.run(account, crypto.randomUUID(), {}, task), e => e.status === 429);
  await assert.rejects(usage.run(account, undefined, {}, task), e => e.status === 400);
  process.env.AI_GLOBAL_DAILY_UNITS = '1';
  await usage.paidCall(async () => 'one unit');
  await assert.rejects(usage.paidCall(async () => 'not reached'), e => e.status === 429);
});
